"""Render an AnalysisResult (dict) to DOCX and PDF.

Used by the post-processing Lambda for the draft, and reusable by the export API
to render the approved version after faculty edits.
"""

from __future__ import annotations

import io
import re

DRAFT_BANNER = "DRAFT - generated by PHACT for faculty review. Not approved for use or distribution."


def _blocks(markdown: str):
    """Yield (kind, text) from the small Markdown subset Agent 3 writes."""
    for raw in markdown.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        heading = re.match(r"^(#{1,4})\s+(.*)", line)
        if heading:
            yield f"h{len(heading.group(1))}", heading.group(2)
        elif re.match(r"^\s*[-*]\s+", line):
            yield "bullet", re.sub(r"^\s*[-*]\s+", "", line)
        elif re.match(r"^\s*\|?\s*:?-{3,}", line):
            continue  # table separator row
        else:
            yield "para", line.strip().strip("|").replace(" | ", "  |  ") if line.strip().startswith("|") else line.strip()


def _plain(text: str) -> str:
    return re.sub(r"\*\*(.+?)\*\*|__(.+?)__", lambda m: m.group(1) or m.group(2), text)


def _citation_line(citation: dict) -> str:
    page = f", p. {citation['page']}" if citation.get("page") else ""
    return f"[{citation['id']}] {citation['title']}{page} - {citation['kind']}"


def render_docx(result: dict, banner: str = DRAFT_BANNER) -> bytes:
    import docx
    from docx.shared import RGBColor

    revised = result.get("revisedSyllabus") or {}
    document = docx.Document()
    document.add_heading(revised.get("title") or "Revised syllabus", level=0)
    note = document.add_paragraph().add_run(banner)
    note.bold = True
    note.font.color.rgb = RGBColor(0xB0, 0x30, 0x30)

    if revised.get("changeSummary"):
        document.add_heading("Summary of changes", level=1)
        for change in revised["changeSummary"]:
            document.add_paragraph(_plain(change), style="List Bullet")

    for kind, text in _blocks(revised.get("markdown", "")):
        if kind.startswith("h"):
            document.add_heading(_plain(text), level=min(int(kind[1]), 3))
        else:
            paragraph = document.add_paragraph(style="List Bullet" if kind == "bullet" else None)
            run = paragraph.add_run(_plain(text))
            if "[PHACT]" in text:
                run.font.color.rgb = RGBColor(0x1F, 0x5F, 0xAF)

    document.add_page_break()
    document.add_heading("Appendix A - AI integration recommendations", level=1)
    for rec in result.get("recommendations", []):
        document.add_heading(f"{rec['title']} ({rec['module']})", level=2)
        document.add_paragraph(rec["description"])
        document.add_paragraph(f"Rationale (AI synthesis): {rec['rationale']}")
        document.add_paragraph(f"Responsible AI: {rec['responsibleAI']}")
        for citation in rec.get("citations", []):
            document.add_paragraph(_citation_line(citation), style="List Bullet")

    if result.get("competencyMappings"):
        document.add_heading("Appendix B - Competency mapping", level=1)
        table = document.add_table(rows=1, cols=4)
        table.style = "Table Grid"
        for cell, label in zip(table.rows[0].cells, ["Objective", "Competency", "Alignment", "Gap / improvement"]):
            cell.text = label
        for mapping in result["competencyMappings"]:
            cells = table.add_row().cells
            cells[0].text = mapping["objective"]
            cells[1].text = f"{mapping['competency']}\nSource: {mapping['source']}"
            cells[2].text = mapping["alignment"]
            cells[3].text = f"{mapping['gap']}\n{mapping['improvement']}"

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


_LATIN1 = str.maketrans({"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-",
                         "•": "-", "…": "...", "→": "->", "−": "-", " ": " ", "≥": ">=",
                         "≤": "<=", "×": "x"})


def _latin1(text: str) -> str:
    return _plain(text).translate(_LATIN1).encode("latin-1", "replace").decode("latin-1")


def render_pdf(result: dict, banner: str = DRAFT_BANNER) -> bytes:
    from fpdf import FPDF

    revised = result.get("revisedSyllabus") or {}
    pdf = FPDF(format="Letter")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin

    def write(text: str, size: float = 10, style: str = "", color=(0, 0, 0), indent: float = 0):
        pdf.set_font("Helvetica", style, size)
        pdf.set_text_color(*color)
        pdf.set_x(pdf.l_margin + indent)
        pdf.multi_cell(width - indent, size * 0.5, _latin1(text))
        pdf.ln(1)

    write(revised.get("title") or "Revised syllabus", 16, "B")
    write(banner, 9, "B", (176, 48, 48))
    if revised.get("changeSummary"):
        write("Summary of changes", 12, "B")
        for change in revised["changeSummary"]:
            write(f"- {change}", indent=4)
    for kind, text in _blocks(revised.get("markdown", "")):
        color = (31, 95, 175) if "[PHACT]" in text else (0, 0, 0)
        if kind.startswith("h"):
            write(text, {"h1": 14, "h2": 12}.get(kind, 11), "B")
        elif kind == "bullet":
            write(f"- {text}", color=color, indent=4)
        else:
            write(text, color=color)

    pdf.add_page()
    write("Appendix A - AI integration recommendations", 13, "B")
    for rec in result.get("recommendations", []):
        write(f"{rec['title']} ({rec['module']})", 11, "B")
        write(rec["description"])
        write(f"Rationale (AI synthesis): {rec['rationale']}", 9)
        for citation in rec.get("citations", []):
            write(_citation_line(citation), 8, color=(80, 80, 80), indent=4)
    if result.get("competencyMappings"):
        write("Appendix B - Competency mapping", 13, "B")
        for mapping in result["competencyMappings"]:
            write(f"{mapping['alignment']}: {mapping['objective']}", 10, "B")
            write(f"{mapping['competency']} - {mapping['gap']}", 9, indent=4)
    return bytes(pdf.output())
